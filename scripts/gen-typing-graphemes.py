#!/usr/bin/env python3
"""Generate Unicode 17 grapheme tables from reviewed UCD inputs, never from host ICU.

Inputs: GraphemeBreakProperty.txt, DerivedCoreProperties.txt, emoji-data.txt.
Source: unicode-org/unicodetools @ 578f6c0516f5f268292ebda50b51848407a06478,
unicodetools/data/ucd/17.0.0/{auxiliary/,emoji/,}*.txt (GitHub contents/blob API).
No network access at build/runtime. Unicode data license: https://www.unicode.org/license.txt
"""
import argparse
import hashlib
from pathlib import Path

EXPECTED_SHA256 = {'GraphemeBreakProperty.txt': 'd6b51d1d2ae5c33b451b7ed994b48f1f4dc62b2272a5831e7fd418514a6bae89', 'DerivedCoreProperties.txt': '24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08', 'emoji-data.txt': '2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b'}

PROPS = {'CR': 1, 'LF': 2, 'Control': 3, 'Extend': 4, 'ZWJ': 5,
         'Regional_Indicator': 6, 'Prepend': 7, 'SpacingMark': 8, 'L': 9, 'V': 10, 'T': 11}

def ranges(path, kind):
    rows = []
    for raw in path.read_text().splitlines():
        fields = [part.strip() for part in raw.split('#', 1)[0].split(';')]
        if len(fields) < 2 or not fields[0]:
            continue
        if kind == 'gcb':
            prop = PROPS.get(fields[1])
        elif kind == 'incb':
            prop = {'Consonant': 1, 'Linker': 2, 'Extend': 3}.get(fields[2]) if len(fields) > 2 and fields[1] == 'InCB' else None
        else:
            prop = 1 if fields[1] == 'Extended_Pictographic' else None
        if prop is not None:
            ends = fields[0].split('..')
            rows.append((int(ends[0], 16), int(ends[-1], 16), prop))
    return sorted(rows)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ucd-dir', type=Path, required=True)
    args = parser.parse_args()
    sources = [('GCB', 'GraphemeBreakProperty.txt', 'gcb'), ('INCB', 'DerivedCoreProperties.txt', 'incb'), ('PICTOGRAPHIC', 'emoji-data.txt', 'ep')]
    out = ['package org.telegram.ui.Components;\n',
           '// Generated by scripts/gen-typing-graphemes.py; Unicode 17.0.0. Do not edit.',
           '// Unicode data © 2025 Unicode, Inc.; https://www.unicode.org/license.txt',
           'final class PengramGraphemeData {', '    private PengramGraphemeData() {}']
    for name, filename, kind in sources:
        path = args.ucd_dir / filename
        if hashlib.sha256(path.read_bytes()).hexdigest() != EXPECTED_SHA256[filename]:
            raise ValueError('Не тот закреплённый Unicode 17 источник: ' + filename)
        out.append('    // ' + filename + ' SHA256 ' + hashlib.sha256(path.read_bytes()).hexdigest())
        out.append('    static final int[] ' + name + ' = {')
        for start, end, prop in ranges(path, kind):
            out.append(f'        0x{start:X}, 0x{end:X}, {prop},')
        out.append('    };')
    out.append('}')
    target = Path(__file__).resolve().parents[1] / 'TMessagesProj/src/main/java/org/telegram/ui/Components/PengramGraphemeData.java'
    target.write_text('\n'.join(out) + '\n')
    print('Generated', target.name)

if __name__ == '__main__':
    main()
